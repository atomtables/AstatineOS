void outportb(u16 port, u8 data) {
    asm ("outb %1, %0" : : "dN" (port), "a" (data));
}
void initialise_color_palette() {
    // all palette registers
    outportb(PALETTE_MASK_REG, 0xff);
    outportb(PALETTE_WRITE_REG, 0);
    for (int i = 0; i < 256; i++) {
        // red
        outportb(PALETTE_DATA_REG, (i >> 5 & 0x07) * 9);
        // green
        outportb(PALETTE_DATA_REG, (i >> 2 & 0x07) * 9);
        // blue
        outportb(PALETTE_DATA_REG, (i & 0x03) * 21);
    }
}

