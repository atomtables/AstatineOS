// straight from gemini for max efficiency
void draw_a_character_opaque(u32 x, u32 y, u8 item[7][5], u8 fg, u8 bg) {
    volatile u8* fb = (u8*)(0xa0000 + y * 320 + x);

    // 1. Splat the 8-bit colors into 32-bit and 16-bit register sizes
    u32 fg4 = fg | (fg << 8) | (fg << 16) | (fg << 24);
    u32 bg4 = bg | (bg << 8) | (bg << 16) | (bg << 24);
    u16 bg2 = bg | (bg << 8);

    // 2. Render the first 7 rows (Glyph data + Right padding column)
    for (int i = 0; i < 7; i++) {
        // Grab pixels 0, 1, 2, 3 in one 32-bit read
        u32 mask4 = *(const u32*)&item[i][0];
        *(volatile u32*)fb = (mask4 & fg4) | (~mask4 & bg4);

        // Process the 5th pixel from the glyph array
        u8 mask1 = item[i][4];
        fb[4] = (mask1 & fg) | (~mask1 & bg);

        // Inject the 6th pixel (Right padding column) directly as background
        fb[5] = bg;

        // Jump down to the next row on the screen
        fb += 320;
    }

    // 3. Render the 8th row (Entire bottom padding row)
    // Write 4 bytes of background color, then 2 bytes of background color
    *(volatile u32*)fb = bg4;
    *(volatile u16*)(fb + 4) = bg2;
}

