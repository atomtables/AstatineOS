bool set_string(TeletypeDriver* self, u32 x, u32 y, const char* str, u8 color) {
    u32 cur_x = x;
    u32 cur_y = y;
    for (u32 i = 0; str[i] != 0; i++) {
        if (str[i] == '\n') {
            cur_x = x;
            cur_y++;
            continue;
        }
        if (!set_char(self, cur_x, cur_y, (u8)str[i], color)) {
            return false;
        }
        cur_x++;
        if (cur_x >= mode.width) {
            cur_x = x;
            cur_y++;
        }
        if (cur_y >= mode.height) {
            return false;
        }
    }
    return true;
}

