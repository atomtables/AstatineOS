void memset_kys(volatile void* dst, u8 value, u32 n) {
    u32 v32 = value | (value << 8) | (value << 16) | (value << 24);
    u32 words = n >> 2;
    u32 bytes = n & 3;

    asm (
        "cld\n\t"
        "rep stosl\n\t"
        "movl %2, %%ecx\n\t"
        "rep stosb"
        : "+D"(dst), "+c"(words)
        : "r"(bytes), "a"(v32)
        : "memory"
    );
}

